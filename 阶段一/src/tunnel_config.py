# 7. 无量纲量辅助（后续阶段统一引用，此处集中定义避免口径不一）
# ============================================================================
def froude(U):
    """无量纲风速 Fr = U/sqrt(gH)。"""
    return U / (G * H) ** 0.5


def q_star_convective(Q_c):
    """无量纲对流火源功率 Q_c* = Q_c / [rho0 cp T0 sqrt(g) H^(5/2)]  [W]→无量纲。"""
    denom = RHO_0 * CP * T_AMBIENT_K * (G ** 0.5) * (H ** 2.5)
    return Q_c / denom


def critical_velocity_estimate(Q):
    """
    临界风速 U_c 粗估（§2.2 / §8.2 前期预计算用）。
    采用 Kennedy/Wu-Bakar 类关联的简化形式，仅用于工况分层与临界区加密，
    不作为论文最终结论；实际 U_c 由 FDS 回流长度判定。
    Q 单位 MW。
    """
    # U_c ≈ 0.0188·(g·H)^{1/2}·(Q^*/... ) 经验取近似式（工程粗估）：
    # 采用常见形式 U_c [m/s] ≈ K * (g·Q·H / (rho cp T))^1/3 的简化常数。
    # 这里仅给一个稳定、量级合理的粗估值用于分层。
    Qw = Q * 1e6  # W
    K = 0.044
    return K * (G * Qw * H / (RHO_0 * CP * T_AMBIENT_K)) ** (1.0 / 3.0)


