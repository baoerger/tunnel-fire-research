def sensor_layout(near_step=0.5 * H, far_step=1.0 * H,
                 fire_x=None, region=None):
    """
    生成顶棚中心线虚拟测点 x 坐标（§1.7）。

    - 火源可能区（中部约 ±2~4H，即 x≈30~70）附近间距 0.25H~0.5H；
    - 远离火源后放宽至 H~2H；
    - 全部落在均匀测量区 [15, 85] 内，不得越过洞口缓冲。

    返回有序 x 列表（长度 20~30）。
    """
    if fire_x is None:
        fire_x = X_FIRE_DEFAULT
    if region is None:
        region = MEAS_REGION
    lo, hi = region

    # 近场加密区：火源 ±4H，但限制在测量区内
    near_lo = max(lo, fire_x - 4.0 * H)
    near_hi = min(hi, fire_x + 4.0 * H)

    pts = set()

    def _range(a, b, step):
        # 含端点的等距点
        n = int(round((b - a) / step))
        for i in range(n + 1):
            pts.add(round(a + i * step, 4))

    # 远场左 [lo, near_lo]、近场 [near_lo, near_hi]、远场右 [near_hi, hi]
    if near_lo > lo:
        _range(lo, near_lo, far_step)
    _range(near_lo, near_hi, near_step)
    if near_hi < hi:
        _range(near_hi, hi, far_step)

    # 保证关键点存在：火源点、测量区端点
    pts.add(round(fire_x, 4))
    pts.add(round(lo, 4))
    pts.add(round(hi, 4))

    return sorted(pts)


